export function sanitizeMetadataValue(val: string | undefined | null): string {
  if (!val) return '';
  let cleaned = String(val).trim();
  // Strip French typographic guillemets, escaped quotes, backslashes, and spacing
  const quotePattern = /^[\u00AB\u00BB\"\'\u201C\u201D\u2018\u2019\s\\\xa0\u202F\u2007\u200B]+|[\u00AB\u00BB\"\'\u201C\u201D\u2018\u2019\s\\\xa0\u202F\u2007\u200B]+$/g;
  let last = '';
  while (cleaned !== last) {
    last = cleaned;
    cleaned = cleaned.replace(quotePattern, '').trim();
  }
  return cleaned;
}

export const formatCourseLevel = (level: string | number | undefined | null, lang: string): string => {
  if (!level) return '';
  let cleanLvl = sanitizeMetadataValue(String(level));
  let lvlStr = cleanLvl.toLowerCase();
  const langKey = lang.toUpperCase();

  // Normalize common legacy and French school system abbreviations dynamically to canonical levels
  const normalKeyMap: Record<string, string> = {
    'beginner': 'l1',
    'intermediate': 'l2',
    'advanced': 'l3',
    'expert': 'm1',
    'cp': 'foundation_1',
    'ce1': 'foundation_1',
    'ce2': 'foundation_1',
    'cm1': 'foundation_2',
    'cm2': 'foundation_2',
    'collège': 'secondary_1',
    'college': 'secondary_1',
    'lycée': 'preuni_1',
    'lycee': 'preuni_1',
    'seconde': 'preuni_1',
    'première': 'preuni_2',
    'premiere': 'preuni_2',
    'terminale': 'preuni_3',
    'supérieur': 'l1',
    'superieur': 'l1',
    'universitaire': 'l1',
    'university': 'l1',
    'bachelor': 'l3',
    'licence': 'l3'
  };

  if (normalKeyMap[lvlStr]) {
    lvlStr = normalKeyMap[lvlStr];
  }

  // 1. Try localStorage translation cache first
  if (typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem(`op_lang_levels_${langKey}`);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (parsed[level]) return parsed[level];
        if (parsed[lvlStr]) return parsed[lvlStr];
      }
    } catch (e) {
      console.error(e);
    }
  }

  // 2. Try static list match (including L1-M2 etc. to keep everything aligned with STATIC_ACADEMIC_LEVELS)
  const found = STATIC_ACADEMIC_LEVELS.find(l => l.value.toLowerCase() === lvlStr);
  if (found) {
    return (found as any)[langKey] || found.EN;
  }

  const isEn = langKey === 'EN';
  const isZh = langKey === 'ZH';
  const isEs = langKey === 'ES';
  const isDe = langKey === 'DE';
  const isFr = langKey === 'FR';
  const isPt = langKey === 'PT';
  const isAr = langKey === 'AR';
  const isHi = langKey === 'HI';
  const isUr = langKey === 'UR';

  if (lvlStr.startsWith('secondary_')) {
    const num = lvlStr.split('_')[1];
    if (isFr) return `Secondaire ${num}`;
    if (isZh) return `中学 ${num}`;
    if (isEs) return `Secundaria ${num}`;
    if (isDe) return `Sekundarstufe ${num}`;
    if (isPt) return `Secundário ${num}`;
    if (isAr) return `ثانوي ${num}`;
    if (isHi) return `माध्यमिक ${num}`;
    if (isUr) return `سیکنڈری ${num}`;
    return `Secondary ${num}`;
  }
  if (lvlStr.startsWith('primary_')) {
    const num = lvlStr.split('_')[1];
    if (isFr) return `Primaire ${num}`;
    if (isZh) return `小学 ${num}`;
    if (isEs) return `Primaria ${num}`;
    if (isDe) return `Primarstufe ${num}`;
    if (isPt) return `Primário ${num}`;
    if (isAr) return `ابتدائي ${num}`;
    if (isHi) return `प्राथमिक ${num}`;
    if (isUr) return `پرائمری ${num}`;
    return `Primary ${num}`;
  }

  if (/^\d+$/.test(lvlStr)) {
    const num = parseInt(lvlStr, 10);
    if (isZh) return `${num}年级`;
    if (isEn) return `Grade ${num}`;
    if (isFr) return `Niveau ${num}`;
    if (isEs) return `Grado ${num}`;
    if (isDe) return `Klasse ${num}`;
    if (isPt) return `Ano ${num}`;
    if (isAr) return `الصف ${num}`;
    if (isHi) return `कक्षा ${num}`;
    if (isUr) return `کلاس ${num}`;
  }

  return lvlStr.toUpperCase();
};

